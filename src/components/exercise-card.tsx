"use client";

import { useRef, useState } from "react";

import { countWords } from "@/lib/domain/text";
import type { AttemptFeedback } from "@/lib/services/feedback";
import type { SessionExerciseView } from "@/lib/services/sessions";
import { FeedbackPanel } from "./feedback-panel";

const TYPE_LABEL: Record<string, string> = {
  fill_blank: "Fill in the blank",
  translation: "Translation",
  sentence_correction: "Correction",
  reading_mcq: "Reading",
  short_writing: "Writing",
  reflection: "Reflection",
};

async function postJson<T>(url: string, body: unknown): Promise<T> {
  const res = await fetch(url, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify(body) });
  const data = await res.json();
  if (!res.ok) throw new Error(data.error ?? `Request failed (${res.status})`);
  return data as T;
}

export function ExerciseCard({ item, index, onChanged }: { item: SessionExerciseView; index: number; onChanged: () => void }) {
  const c = item.content;
  const initial = item.lastAttempt?.canRevise ? item.lastAttempt.response : c.type === "sentence_correction" ? c.prompt : "";
  const [response, setResponse] = useState(initial);
  const [feedback, setFeedback] = useState<AttemptFeedback | null>(item.lastAttempt);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [showHint, setShowHint] = useState(false);
  const startedAt = useRef<number>(0);

  const done = item.status === "completed" || feedback?.status === "applied" || feedback?.status === "recorded";
  const awaitingRevision = Boolean(feedback?.canRevise);
  const locked = done && !awaitingRevision;

  function touch() {
    if (!startedAt.current) startedAt.current = Date.now();
  }

  async function submit(opts: { parentAttemptId?: string } = {}) {
    setBusy(true);
    setError(null);
    try {
      const fb = await postJson<AttemptFeedback>("/api/attempts", {
        exerciseId: item.id,
        response,
        latencyMs: startedAt.current ? Date.now() - startedAt.current : null,
        hintsUsed: showHint ? 1 : 0,
        parentAttemptId: opts.parentAttemptId,
      });
      setFeedback(fb);
      onChanged();
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setBusy(false);
    }
  }

  async function reveal() {
    if (!feedback) return;
    setBusy(true);
    try {
      const res = await fetch(`/api/attempts/${feedback.attemptId}?reveal=1`);
      setFeedback(await res.json());
    } finally {
      setBusy(false);
    }
  }

  const words = countWords(response);

  return (
    <article className="card space-y-4" data-testid="exercise" data-type={c.type} data-status={locked ? "done" : "open"}>
      <header className="flex flex-wrap items-center gap-2 text-xs text-muted">
        <span className="font-medium text-text">
          {index + 1}. {TYPE_LABEL[c.type] ?? c.type}
        </span>
        {item.conceptTitle && <span className="chip">{item.conceptTitle}</span>}
        {item.sourceType === "generated" && (
          <span className="chip" title="Generated by the AI for this session">
            AI-generated
          </span>
        )}
        {locked && <span className="ml-auto text-good">✓ Done</span>}
      </header>

      <div className="space-y-2">
        <p className="text-sm text-muted">{c.instructions}</p>
        {c.type === "reading_mcq" && <p className="whitespace-pre-wrap rounded-lg bg-surface-2 p-3 leading-relaxed">{c.passage}</p>}
        <p className="text-lg leading-relaxed" data-testid="prompt">
          {c.prompt}
        </p>
        {c.type === "short_writing" && (
          <div className="text-sm text-muted">
            <p>
              {c.minWords}–{c.maxWords} words. Include:
            </p>
            <ul className="ml-5 list-disc">
              {c.requiredElements.map((r) => (
                <li key={r}>{r}</li>
              ))}
            </ul>
          </div>
        )}
      </div>

      {!locked && (
        <form
          className="space-y-3"
          onSubmit={(e) => {
            e.preventDefault();
            void submit(awaitingRevision && feedback ? { parentAttemptId: feedback.attemptId } : {});
          }}
        >
          {c.type === "reading_mcq" ? (
            <fieldset className="space-y-2">
              {c.options.map((o, i) => (
                <label key={i} className="flex cursor-pointer items-center gap-3 rounded-lg border border-line px-3 py-2 hover:bg-surface-2">
                  <input
                    type="radio"
                    name={`mcq-${item.id}`}
                    value={i}
                    checked={response === String(i)}
                    onChange={() => {
                      touch();
                      setResponse(String(i));
                    }}
                  />
                  <span>{o}</span>
                </label>
              ))}
            </fieldset>
          ) : c.type === "fill_blank" ? (
            <input
              className="input"
              aria-label="Your answer"
              value={response}
              onChange={(e) => {
                touch();
                setResponse(e.target.value);
              }}
              placeholder="Missing word(s)"
              autoComplete="off"
              spellCheck={false}
            />
          ) : (
            <textarea
              className="input min-h-24"
              aria-label="Your answer"
              rows={c.type === "short_writing" ? 7 : c.type === "reflection" ? 3 : 2}
              value={response}
              onChange={(e) => {
                touch();
                setResponse(e.target.value);
              }}
              spellCheck={false}
              placeholder={c.type === "translation" ? "Votre traduction" : awaitingRevision ? "Revise your text" : "Votre réponse"}
            />
          )}

          <div className="flex flex-wrap items-center gap-2">
            <button className="btn-primary" disabled={busy || response.trim() === ""} type="submit">
              {busy ? "Checking…" : awaitingRevision ? "Submit revision" : "Submit"}
            </button>
            {awaitingRevision && (
              <button type="button" className="btn-ghost" onClick={() => void reveal()} disabled={busy}>
                Show corrections
              </button>
            )}
            {c.hint && !awaitingRevision && (
              <button type="button" className="btn-ghost" onClick={() => setShowHint(true)} disabled={showHint}>
                Hint
              </button>
            )}
            {(c.type === "short_writing" || c.type === "reflection") && (
              <span className="ml-auto text-xs tabular-nums text-muted" data-testid="word-count">
                {words} word{words === 1 ? "" : "s"}
              </span>
            )}
          </div>
          {showHint && c.hint && <p className="text-sm text-muted">Hint: {c.hint}</p>}
        </form>
      )}

      {error && (
        <p className="text-sm text-bad" role="alert">
          {error}
        </p>
      )}
      {feedback && <FeedbackPanel fb={feedback} exerciseType={c.type} />}
    </article>
  );
}
